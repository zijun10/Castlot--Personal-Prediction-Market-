-- Castlot market engine: LMSR pricing behind a server trust boundary.
-- Clients send trade intent only; cost is computed and settled here, atomically.

-- ── LMSR math ─────────────────────────────────────────────────────────────────

create or replace function public.lmsr_cost(q_yes double precision, q_no double precision, b double precision)
returns double precision
language sql immutable
as $$
  select b * ln(exp(q_yes / b) + exp(q_no / b));
$$;

create or replace function public.lmsr_price(q_yes double precision, q_no double precision, b double precision)
returns double precision
language sql immutable
as $$
  select exp(q_yes / b) / (exp(q_yes / b) + exp(q_no / b));
$$;

-- ── Tables ────────────────────────────────────────────────────────────────────

create table public.markets (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null,
  b double precision not null default 80 check (b > 0),
  q_yes double precision not null default 0,
  q_no double precision not null default 0,
  traders integer not null default 0,
  status text not null default 'trading'
    check (status in ('anchor', 'trading', 'closed', 'resolved')),
  outcome boolean,                       -- null until resolved
  resolution_date date not null,
  audio_summary text,
  transcript jsonb not null default '[]'::jsonb,
  tags jsonb not null default '[]'::jsonb,
  creator_id uuid references auth.users (id) on delete set null,
  creator_alias text not null default 'anon',
  created_at timestamptz not null default now()
);

-- Append-only ledger: FP balance is always sum(amount), never a mutable column.
create table public.fp_ledger (
  id bigint generated always as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  amount double precision not null check (amount <> 0),
  kind text not null check (kind in ('grant', 'decay', 'trade', 'payout')),
  trade_id bigint,
  created_at timestamptz not null default now()
);
create index fp_ledger_user_idx on public.fp_ledger (user_id);

create table public.trades (
  id bigint generated always as identity primary key,
  market_id bigint not null references public.markets (id),
  user_id uuid not null references auth.users (id) on delete cascade,
  side text not null check (side in ('yes', 'no')),
  shares double precision not null check (shares > 0),
  cost double precision not null,
  created_at timestamptz not null default now()
);
create index trades_market_idx on public.trades (market_id);
create index trades_user_idx on public.trades (user_id);

alter table public.fp_ledger
  add constraint fp_ledger_trade_fk foreign key (trade_id) references public.trades (id);

create table public.positions (
  market_id bigint not null references public.markets (id),
  user_id uuid not null references auth.users (id) on delete cascade,
  yes_shares double precision not null default 0,
  no_shares double precision not null default 0,
  primary key (market_id, user_id)
);
create index positions_user_idx on public.positions (user_id);

-- ── Signup grant ──────────────────────────────────────────────────────────────

create or replace function public.handle_new_user()
returns trigger
language plpgsql security definer set search_path = public
as $$
begin
  insert into public.fp_ledger (user_id, amount, kind) values (new.id, 1000, 'grant');
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ── Balance ───────────────────────────────────────────────────────────────────

create or replace function public.fp_balance()
returns double precision
language sql stable security definer set search_path = public
as $$
  select coalesce(sum(amount), 0) from fp_ledger where user_id = auth.uid();
$$;

-- ── Trade execution ───────────────────────────────────────────────────────────
-- The only write path for trading. Locks the market row so concurrent trades on
-- the same market serialize; inventory updates and ledger writes are one
-- transaction, so a failure anywhere rolls back everything.

create or replace function public.execute_trade(
  p_market_id bigint,
  p_side text,
  p_shares double precision
)
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  m public.markets%rowtype;
  v_new_yes double precision;
  v_new_no double precision;
  v_cost double precision;
  v_balance double precision;
  v_trade_id bigint;
  v_new_position boolean;
begin
  if v_user is null then
    raise exception 'not authenticated';
  end if;
  if p_side not in ('yes', 'no') then
    raise exception 'side must be yes or no';
  end if;
  if p_shares is null or p_shares <= 0 or p_shares > 1000 then
    raise exception 'shares must be in (0, 1000]';
  end if;

  select * into m from markets where id = p_market_id for update;
  if not found then
    raise exception 'market % not found', p_market_id;
  end if;
  if m.status <> 'trading' then
    raise exception 'market is % — not open for trading', m.status;
  end if;

  v_new_yes := m.q_yes + case when p_side = 'yes' then p_shares else 0 end;
  v_new_no  := m.q_no  + case when p_side = 'no'  then p_shares else 0 end;
  v_cost := lmsr_cost(v_new_yes, v_new_no, m.b) - lmsr_cost(m.q_yes, m.q_no, m.b);

  select coalesce(sum(amount), 0) into v_balance from fp_ledger where user_id = v_user;
  if v_balance < v_cost then
    raise exception 'insufficient FP: balance %, cost %',
      round(v_balance::numeric, 2), round(v_cost::numeric, 2);
  end if;

  insert into trades (market_id, user_id, side, shares, cost)
    values (p_market_id, v_user, p_side, p_shares, v_cost)
    returning id into v_trade_id;

  insert into fp_ledger (user_id, amount, kind, trade_id)
    values (v_user, -v_cost, 'trade', v_trade_id);

  v_new_position := not exists (
    select 1 from positions where market_id = p_market_id and user_id = v_user
  );
  insert into positions (market_id, user_id, yes_shares, no_shares)
    values (
      p_market_id, v_user,
      case when p_side = 'yes' then p_shares else 0 end,
      case when p_side = 'no'  then p_shares else 0 end
    )
    on conflict (market_id, user_id) do update set
      yes_shares = positions.yes_shares + excluded.yes_shares,
      no_shares  = positions.no_shares  + excluded.no_shares;

  update markets set
    q_yes = v_new_yes,
    q_no = v_new_no,
    traders = traders + case when v_new_position then 1 else 0 end
  where id = p_market_id;

  return jsonb_build_object(
    'trade_id', v_trade_id,
    'cost', v_cost,
    'q_yes', v_new_yes,
    'q_no', v_new_no,
    'traders', m.traders + case when v_new_position then 1 else 0 end,
    'yes_price', lmsr_price(v_new_yes, v_new_no, m.b),
    'balance', v_balance - v_cost
  );
end;
$$;

-- ── Row-level security ────────────────────────────────────────────────────────
-- Markets are public reads. Everything money-shaped is readable only by its
-- owner and writable only through execute_trade (security definer).

alter table public.markets enable row level security;
alter table public.fp_ledger enable row level security;
alter table public.trades enable row level security;
alter table public.positions enable row level security;

create policy "markets are public" on public.markets
  for select using (true);

create policy "create own market with zero inventory" on public.markets
  for insert to authenticated
  with check (
    creator_id = auth.uid()
    and q_yes = 0 and q_no = 0 and traders = 0
    and status = 'trading' and outcome is null
  );

create policy "read own ledger" on public.fp_ledger
  for select using (user_id = auth.uid());

create policy "read own trades" on public.trades
  for select using (user_id = auth.uid());

create policy "read own positions" on public.positions
  for select using (user_id = auth.uid());
